// Clicks through the screen in Chrome with made-up data and saves screenshots to test/shots.
const { chromium } = require('/opt/npm-tools/node_modules/playwright');
const path = require('path');
const fs = require('fs');
(async () => {
  const out = path.join(__dirname, 'shots'); fs.mkdirSync(out, { recursive: true });
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--allow-file-access-from-files'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on('pageerror', e => errors.push('pageerror: ' + e.message));
  page.on('console', m => { if (m.type() === 'error' && !/invalid\.example|fonts\/Atkinson|ERR_FILE_NOT_FOUND|ERR_NAME_NOT_RESOLVED/.test(m.text())) errors.push('console: ' + m.text()); });
  await page.addInitScript({ path: path.join(__dirname, 'ui-mock.js') });
  await page.goto('file://' + path.join(__dirname, '..', 'renderer', 'index.html'));
  await page.waitForSelector('.tile');
  await page.screenshot({ path: path.join(out, '1-records.png') });
  await page.click('.tile >> nth=2');
  await page.click('[data-action="have"][data-v="yes"]');
  await page.click('[data-action="filter"][data-id="need"]');
  await page.screenshot({ path: path.join(out, '2-need-cover.png') });
  const needTiles = await page.$$eval('.tile', t => t.length);
  await page.click('[data-action="filter"][data-id="all"]');
  await page.click('.tile >> nth=0');
  await page.click('[data-action="side"][data-id="back"]');
  await page.screenshot({ path: path.join(out, '3-back-cover.png') });
  await page.fill('#q', 'copper');
  const searchTiles = await page.$$eval('.tile', t => t.length);
  await page.fill('#q', '');
  await page.click('[data-view="add"]');
  await page.screenshot({ path: path.join(out, '4-add.png') });
  await page.fill('#nameq', 'Miles Davis - Kind of Blue');
  await page.click('[data-form="name"] button');
  await page.waitForSelector('.match');
  await page.screenshot({ path: path.join(out, '5-matches.png') });
  await page.click('.match >> nth=0');
  await page.waitForSelector('form[data-form="edit"]');
  await page.screenshot({ path: path.join(out, '6-form-pending.png') });
  const pendingShown = await page.$$eval('.cover-wait', e => e.length);
  await page.waitForSelector('#e-covers img.cover', { timeout: 5000 });
  await page.waitForTimeout(400);
  await page.screenshot({ path: path.join(out, '6-form-top.png') });
  await page.click('[data-action="edit-choice"][data-k="haveCover"][data-v="false"]');
  await page.click('[data-action="edit-choice"][data-k="condition"][data-v="nm"]');
  const condValue = await page.textContent('#e-value .amt');
  await page.fill('#e-paid', '$3 at a church sale');
  await page.evaluate(() => document.querySelector('#e-value').scrollIntoView());
  await page.screenshot({ path: path.join(out, '6b-form-value.png') });
  await page.fill('#e-myValue', '275');
  const ownValue = await page.textContent('#e-value .amt');
  await page.fill('#e-myValue', '');
  await page.click('.save-bar button[type="submit"]');
  await page.waitForSelector('.tile');
  const firstTitle = await page.textContent('.tile .t');
  await page.screenshot({ path: path.join(out, '7-added.png') });
  // edit an existing record that has no value
  await page.click('.tile:has-text("Copper Canyon")');
  const copperTile = await page.textContent('.tile:has-text("Copper Canyon")');
  await page.screenshot({ path: path.join(out, '7b-no-value.png') });
  await page.click('[data-action="edit"]');
  await page.waitForSelector('form[data-form="edit"]');
  await page.click('[data-action="edit-check-value"]');
  await page.waitForTimeout(600);
  const checked = await page.textContent('#e-value');
  await page.click('[data-action="edit-cancel"]');
  await page.click('[data-modal="yes"]');
  await page.waitForSelector('.tile');
  await page.click('[data-view="wish"]');
  await page.screenshot({ path: path.join(out, '8-wish.png') });
  await page.click('[data-view="report"]');
  await page.screenshot({ path: path.join(out, '9-report.png') });
  await page.click('[data-view="settings"]');
  await page.click('[data-action="test-discogs"]');
  await page.waitForTimeout(400);
  const testResult = await page.textContent('#dtest');
  await page.screenshot({ path: path.join(out, '10a-settings-test.png') });
  await page.click('[data-action="text-bigger"]');
  await page.screenshot({ path: path.join(out, '10-settings-big.png') });
  await page.click('[data-view="records"]');
  await page.click('[data-action="delete"]');
  await page.screenshot({ path: path.join(out, '11-delete-confirm.png') });
  await page.click('[data-modal="no"]');
  await page.setViewportSize({ width: 1024, height: 700 });
  await page.click('[data-action="text-smaller"]'); await page.click('[data-action="text-smaller"]');
  await page.screenshot({ path: path.join(out, '12-small-window.png') });
  // ---- import a list ----
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.click('[data-action="text-bigger"]');
  await page.click('[data-view="import"]');
  await page.screenshot({ path: path.join(out, '14-import-start.png') });
  await page.setInputFiles('input[accept=".csv,.tsv,.txt,text/csv"]', path.join(__dirname, 'sample-list.csv'));
  await page.waitForSelector('#imp-preview');
  const foundCount = await page.textContent('.wide-panel h2');
  await page.screenshot({ path: path.join(out, '15-import-map.png'), fullPage: false });
  await page.click('[data-action="imp-start"]');
  await page.waitForTimeout(1200);
  await page.screenshot({ path: path.join(out, '16-import-running.png') });
  await page.waitForSelector('[data-action="imp-see"]', { timeout: 30000 });
  const runSummary = await page.textContent('#imp-run');
  await page.screenshot({ path: path.join(out, '17-import-done.png') });
  await page.click('[data-action="imp-see-check"]');
  await page.waitForSelector('.tile');
  const checkTiles = await page.$$eval('.tile .t', t => t.map(x => x.textContent));
  await page.screenshot({ path: path.join(out, '18-needs-checking.png') });
  await page.click('[data-action="filter"][data-id="all"]');
  const allTitles = await page.$$eval('.tile .t', t => t.map(x => x.textContent));
  await page.click('[data-view="help"]');
  await page.screenshot({ path: path.join(out, '13-help.png') });
  console.log(JSON.stringify({ pendingShown, foundCount, runSummary, checkTiles, allTitles, needTiles, searchTiles, firstTitle, condValue, ownValue, copperTile, checked, testResult, errors }, null, 1));
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
