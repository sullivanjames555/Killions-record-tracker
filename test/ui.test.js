// Clicks through the screen in Chrome with made-up data and saves screenshots to test/shots.
const { chromium } = require('/opt/npm-tools/node_modules/playwright');
const path = require('path');
const fs = require('fs');
(async () => {
  const out = path.join(__dirname, 'shots'); fs.mkdirSync(out, { recursive: true });
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--allow-file-access-from-files'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on('pageerror', e => errors.push('pageerror: ' + e.message));
  page.on('console', m => { if (m.type() === 'error' && !/invalid\.example|fonts\/Atkinson|ERR_FILE_NOT_FOUND|ERR_NAME_NOT_RESOLVED/.test(m.text())) errors.push('console: ' + m.text()); });
  await page.addInitScript({ path: path.join(__dirname, 'ui-mock.js') });
  await page.goto('file://' + path.join(__dirname, '..', 'renderer', 'index.html'));
  await page.waitForSelector('.tile');
  await page.screenshot({ path: path.join(out, '1-records.png') });
  await page.click('.tile >> nth=2');
  await page.click('[data-action="have"][data-v="yes"]');
  await page.click('[data-action="filter"][data-id="need"]');
  await page.screenshot({ path: path.join(out, '2-need-cover.png') });
  const needTiles = await page.$$eval('.tile', t => t.length);
  await page.click('[data-action="filter"][data-id="all"]');
  await page.click('.tile >> nth=0');
  await page.click('[data-action="side"][data-id="back"]');
  await page.screenshot({ path: path.join(out, '3-back-cover.png') });
  await page.fill('#q', 'copper');
  const searchTiles = await page.$$eval('.tile', t => t.length);
  await page.fill('#q', '');
  await page.click('[data-view="add"]');
  await page.screenshot({ path: path.join(out, '4-add.png') });
  await page.fill('#nameq', 'Miles Davis - Kind of Blue');
  await page.click('[data-form="name"] button');
  await page.waitForSelector('.match');
  await page.screenshot({ path: path.join(out, '5-matches.png') });
  await page.click('.match >> nth=0');
  await page.waitForSelector('[data-action="save-draft"]');
  await page.click('[data-action="draft-have"][data-v="no"]');
  await page.waitForTimeout(1900);
  await page.screenshot({ path: path.join(out, '6-found.png') });
  await page.click('[data-action="save-draft"]');
  await page.waitForSelector('.tile');
  const firstTitle = await page.textContent('.tile .t');
  await page.screenshot({ path: path.join(out, '7-added.png') });
  await page.click('[data-view="wish"]');
  await page.screenshot({ path: path.join(out, '8-wish.png') });
  await page.click('[data-view="report"]');
  await page.screenshot({ path: path.join(out, '9-report.png') });
  await page.click('[data-view="settings"]');
  await page.click('[data-action="text-bigger"]');
  await page.screenshot({ path: path.join(out, '10-settings-big.png') });
  await page.click('[data-view="records"]');
  await page.click('[data-action="delete"]');
  await page.screenshot({ path: path.join(out, '11-delete-confirm.png') });
  await page.click('[data-modal="no"]');
  await page.setViewportSize({ width: 1024, height: 700 });
  await page.click('[data-action="text-smaller"]'); await page.click('[data-action="text-smaller"]');
  await page.screenshot({ path: path.join(out, '12-small-window.png') });
  await page.click('[data-view="help"]');
  await page.screenshot({ path: path.join(out, '13-help.png') });
  console.log(JSON.stringify({ needTiles, searchTiles, firstTitle, errors }, null, 1));
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
